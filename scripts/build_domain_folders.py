#!/usr/bin/env python3
"""RF-8 (Oct 27 2026, plan Realm Frame & Folder Architecture): one folder per
app domain for Claude Code sessions - docs/domains/<domain>/README.md lists that
domain's facts file, modules, the prompt files its modules use, and the
Supabase tables they touch. Generated from rpgace_core.js and prompts/, never
hand-edited, so it can't go stale silently (--check fails when it would change).
The facts themselves stay in docs/claude/<domain>.md (CLAUDE.md's index).

  python3 scripts/build_domain_folders.py          write
  python3 scripts/build_domain_folders.py --check  exit 1 if any README is stale
"""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_module_domains import domain_labels, module_domains  # one source of truth
import sys as _sys, os as _os; _sys.path.insert(0, _os.path.dirname(_os.path.abspath(__file__)))
import core_source  # CK-8: the one reader of the client source

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CORE = core_source.read()
OUT = os.path.join(ROOT, 'docs', 'domains')


def module_source(name):
    a = CORE.find('/* ===MODULE:%s=== */' % name)
    b = CORE.find('/* ===END:%s=== */' % name, a)
    return CORE[a:b] if a >= 0 and b > a else ''


def sub_files(dom):
    """CK-2 (Oct 28 2026): a hub's sub-files (first line says 'sub-file of the ... hub (`docs/claude/<dom>.md`)'),
    listed as the next rung of the ladder."""
    subs = []
    folder = os.path.join(ROOT, 'docs', 'claude')
    for name in sorted(os.listdir(folder)):
        if not name.endswith('.md'):
            continue
        head = open(os.path.join(folder, name), encoding='utf-8').read().split('\n', 1)[0]
        if 'sub-file of' in head and '`docs/claude/%s.md`' % dom in head:
            subs.append('[`%s`](../../claude/%s)' % (name, name))
    return (' → ' + ', '.join(subs)) if subs else ''


def readme(dom, label, mods):
    prompts, tables = set(), set()
    for m in mods:
        src = module_source(m)
        prompts.update(re.findall(r"RPGACE\.prompt\('(\w+)'", src))
        tables.update(re.findall(r"(?:sb\.select|secureWrite|sb\.insert|sb\.update|sb\.del|read)\(\s*'([a-z_]+)'", src))
    lines = ['# %s (`%s`)' % (label, dom), '',
             'Generated by `scripts/build_domain_folders.py` - do not edit. The folder-as-agent view of this domain:',
             'what to read before working on it.', '',
             '- **Facts:** [`docs/claude/%s.md`](../../claude/%s.md)' % (dom, dom) + sub_files(dom),
             '- **Maps:** %s' % (', '.join(x for x in [
                 '[`interconnections.md`](interconnections.md)' if os.path.exists(os.path.join(ROOT, 'docs', 'domains', dom, 'interconnections.md')) else '',
                 '[`flow.md`](flow.md)' if os.path.exists(os.path.join(ROOT, 'docs', 'domains', dom, 'flow.md')) else ''] if x) or 'cross-domain only (root interconnection_map.md / system_flow_map.md)'),
             '- **Modules (%d):** %s' % (len(mods), ', '.join('`%s`' % m for m in sorted(mods)) or 'none'),
             '- **Prompts:** %s' % (', '.join('[`%s`](../../../prompts/%s.md)' % (p, p) for p in sorted(prompts)) or 'none in prompts/ yet (see prompts/INDEX.md for inline ones)'),
             '- **Tables touched:** %s' % (', '.join('`%s`' % t for t in sorted(tables)) or 'none found'),
             '- **Realm registry:** `realm_lenses.json` (each realm\'s frame: target, tools, feeds, starters)', '']
    return '\n'.join(lines)


def main():
    labels = domain_labels(CORE)
    by = {}
    for mod, dom in module_domains(CORE).items():
        by.setdefault(dom, []).append(mod)
    stale = []
    for dom, label in labels.items():
        path = os.path.join(OUT, dom, 'README.md')
        new = readme(dom, label, by.get(dom, []))
        old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if old != new:
            stale.append(dom)
            if '--check' not in sys.argv:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, 'w', encoding='utf-8').write(new)
    if '--check' in sys.argv:
        print('DOMAIN FOLDERS CHECK: ' + ('stale: ' + ', '.join(stale) if stale else '%d domains in sync' % len(labels)))
        sys.exit(1 if stale else 0)
    print('domain folders: %d written (%d changed)' % (len(labels), len(stale)))


if __name__ == '__main__':
    main()
