#!/usr/bin/env python3
"""RF-7 (Oct 27 2026, plan Realm Frame & Folder Architecture): prompts/*.md is the
one home for the app's shared Oracle prompts (the folder-as-agent idea: plain
text files a harness or a person can read). This copies them into
rpgace_core.js between the PROMPTS markers (the app has no build step and loads
one script), and writes prompts/INDEX.md: every prompt file plus every other
"You are ..." persona still written inline in code, so nothing is hidden.
Edits happen only through Claude Code (Alex, Oct 27: "Only via Claude Code").

  python3 scripts/build_prompts.py          write
  python3 scripts/build_prompts.py --check  exit 1 if rpgace_core.js or INDEX.md is stale
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PDIR = os.path.join(ROOT, 'prompts')
CORE = os.path.join(ROOT, 'rpgace_core.js')
START = '  /* ===PROMPTS (generated by scripts/build_prompts.py from prompts/*.md - edit those files, not this)=== */'
END = '  /* ===END PROMPTS=== */'


def load():
    out, about = {}, {}
    for f in sorted(os.listdir(PDIR)):
        if not f.endswith('.md') or f in ('README.md', 'INDEX.md'):
            continue
        txt = open(os.path.join(PDIR, f), encoding='utf-8').read()
        m = re.match(r'\s*<!--(.*?)-->\n?', txt, re.S)
        if m:
            about[f[:-3]] = m.group(1).strip()
            txt = txt[m.end():]
        out[f[:-3]] = txt.rstrip('\n')
    return out, about


def block(prompts):
    return START + '\n  R.PROMPTS = ' + json.dumps(prompts, ensure_ascii=False, sort_keys=True) + ';\n' + END


def inline_personas():
    rows = []
    for rel in ['rpgace_core.js'] + ['api/' + f for f in sorted(os.listdir(os.path.join(ROOT, 'api'))) if f.endswith('.js')] + \
               ['local_server/rpgace_intel.py', 'scripts/intel_cc_worker.py']:
        p = os.path.join(ROOT, rel)
        if not os.path.exists(p):
            continue
        seen = set()
        for m in re.finditer(r"You are (?:a |an |the |Oracle|Alex)[^'\"\\\n]{0,60}", open(p, encoding='utf-8').read()):
            s = m.group(0).strip()
            if s in seen or 'INSTA' in s:
                continue
            seen.add(s)
            rows.append((rel, s))
    return rows


def index(prompts, about):
    lines = ['# Prompts', '',
             'Generated by `scripts/build_prompts.py` - do not edit by hand. Prompt files here are copied into',
             '`rpgace_core.js` (`RPGACE.prompt(name, vars)`); `{word}` in a file is filled from vars. Edit only via Claude Code.',
             'Realm lenses (what Oracle looks for per realm) live in `realm_lenses.json`; the video/page analysis prompt is',
             'built in `local_server/rpgace_intel.py` `insights_prompt`.', '', '## Prompt files', '']
    for k in sorted(prompts):
        lines.append('- `%s.md` - %s' % (k, about.get(k, '').split('. Loaded via')[0]))
    lines += ['', '## Still written inline in code (candidates to move here)', '']
    for rel, s in inline_personas():
        lines.append('- `%s`: "%s..."' % (rel, s))
    return '\n'.join(lines) + '\n'


def main():
    prompts, about = load()
    core = open(CORE, encoding='utf-8').read()
    a, b = core.find(START), core.find(END)
    if a < 0 or b < 0:
        sys.exit('PROMPTS markers missing from rpgace_core.js')
    new_core = core[:a] + block(prompts) + core[b + len(END):]
    new_index = index(prompts, about)
    ipath = os.path.join(PDIR, 'INDEX.md')
    old_index = open(ipath, encoding='utf-8').read() if os.path.exists(ipath) else ''
    if '--check' in sys.argv:
        stale = [n for n, o, nw in (('rpgace_core.js', core, new_core), ('prompts/INDEX.md', old_index, new_index)) if o != nw]
        print('PROMPTS CHECK: ' + ('stale: ' + ', '.join(stale) if stale else '%d prompt files, in sync' % len(prompts)))
        sys.exit(1 if stale else 0)
    if new_core != core:
        open(CORE, 'w', encoding='utf-8').write(new_core)
    open(ipath, 'w', encoding='utf-8').write(new_index)
    print('prompts: %d files -> rpgace_core.js + prompts/INDEX.md' % len(prompts))


if __name__ == '__main__':
    main()
