// actually goes wrong while Alex is using RPGACE), not a development-
// process concept - it belongs here the same way it would in any
// production web app. Deliberately minimal for this first real slice:
// global window.onerror/unhandledrejection only. Per-API-endpoint
// server-side error capture (api/*.js) is real, scoped future work, not
// built blind in this pass - see CLAUDE.md's Open forks.
